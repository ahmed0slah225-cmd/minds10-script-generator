"""
engine/engines/research.py
-----------------------------
البحث في خدمة الفكرة، مش العكس. المحرك ده بياخد المصادر اللي جابها
المستخدم (نصوص، روابط، نطاقات PDF مستخرجة) ويحدد إيه المعلومات المفيدة
فعلًا للفكرة، وإيه الفجوات اللي محتاجة بحث خارجي (لو مسموح بيه).

مفيش اختراع لمصادر: أي معلومة من مصدر خارجي غير موجود فعليًا في
`sources_text` أو نتيجة بحث حقيقي، تتوصف كـ "غير موثقة".
"""

from engine import gemini_client
from config import WEB_SEARCH_ENABLED

SYSTEM = (
    "إنت محرك بحث داخل نظام Minds10. مهمتك تحديد المعلومات المفيدة فعلًا "
    "لخدمة فكرة الفيديو من المصادر المتاحة، وتحديد الفجوات المعرفية "
    "بوضوح. ممنوع اختراع دراسة أو رقم أو اقتباس غير موجود في المصادر "
    "المزودة. لو معلومة غير مؤكدة، وصفها صراحة كـ 'غير موثقة'."
)


def run_research(
    topic_understanding: str,
    sources_text: str,
    web_search_allowed: bool = WEB_SEARCH_ENABLED,
) -> str:
    web_note = (
        "البحث الخارجي على الويب مسموح به في هذه الجلسة — لو استخدمته "
        "(افتراضيًا) وضّح أنه معلومة عامة معروفة وليس من مصدر المستخدم."
        if web_search_allowed else
        "البحث الخارجي على الويب غير مفعّل في هذه الجلسة. اعتمد فقط على "
        "المصادر المتاحة أدناه، ولو فيه فجوة معرفية وضّحها بدل ملئها."
    )
    prompt = f"""
فهم الموضوع:
\"\"\"{topic_understanding}\"\"\"

المصادر المتاحة من المستخدم (نصوص / نتائج استخراج PDF / روابط):
\"\"\"{sources_text or "لا توجد مصادر مرفقة من المستخدم."}\"\"\"

{web_note}

المطلوب:
1. استخرج أهم المعلومات والأدلة اللي تخدم الفكرة تحديدًا (مش أي معلومة
   عامة عن الموضوع) — لكل معلومة اذكر: المعلومة، ليها علاقة بإيه في
   الفكرة، ومن أي مصدر جاية (أو "غير موثقة" لو مفيش مصدر واضح).
2. حدد الفجوات المعرفية: إيه اللي الفيديو محتاجه ومش موجود في المصادر.
3. لا تُخرج قائمة طويلة لمجرد الكمية — فقط ما يخدم الفكرة فعلًا.
"""
    return gemini_client.generate(prompt, system_instruction=SYSTEM, temperature=0.4)
