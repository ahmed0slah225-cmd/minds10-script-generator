"""
engine/engines/audience.py
------------------------------
السؤال هنا مش "إيه اللي نعرفه عن الموضوع" بل "المشاهد ليه يقعد يسمع
كل ده؟". المحرك ده بيحدد نقطة الألم أو الفضول الحقيقية اللي هتخلي
الجمهور المحدد يكمل الفيديو، ويظبط مستوى الشرح على حسب الجمهور والمدة.
"""

from engine import gemini_client

SYSTEM = (
    "إنت محرك تحليل الجمهور داخل نظام Minds10. مهمتك تحديد سبب اهتمام "
    "المشاهد الحقيقي، ونقطة الألم أو الفضول اللي تخليه يكمل، مع ضبط "
    "مستوى الشرح على حسب الجمهور والمدة المحددة."
)


def analyze_audience(
    topic_understanding: str,
    audience: str,
    duration_minutes: int,
    knowledge_summary: str,
) -> str:
    prompt = f"""
فهم الموضوع:
\"\"\"{topic_understanding}\"\"\"

الجمهور المستهدف: {audience}
مدة الفيديو: {duration_minutes} دقيقة

ملخص أهم عناصر المعرفة المتاحة:
\"\"\"{knowledge_summary}\"\"\"

المطلوب:
1. حدد نقطة الألم أو الفضول الحقيقية الأقرب لهذا الجمهور تحديدًا (وليس
   جمهور عام مبهم).
2. اكتب جملة أو جملتين تلخّص "ليه المشاهد يكمل" (الوعد الضمني للفيديو).
3. اقترح مستوى الشرح المناسب: عمق الأمثلة، المفردات، سرعة تقديم
   المعلومات، بناءً على الجمهور والمدة.
4. لا تكتب هوك أو سكريبت هنا — فقط تحليل جمهور.
"""
    return gemini_client.generate(prompt, system_instruction=SYSTEM, temperature=0.6)
