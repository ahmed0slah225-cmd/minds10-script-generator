"""
engine/engines/input_understanding.py
---------------------------------------
أول مرحلة في الـ Pipeline. مش بتكتب حاجة نهائية، بتفكك المدخل الخام
(عنوان / فكرة / سؤال / نص) وتحدد: الموضوع الظاهري، والمشكلة الإنسانية
الحقيقية تحته، والاحتمالات المختلفة للزاوية.
"""

from engine import gemini_client

SYSTEM = (
    "إنت محرك فهم المدخلات داخل نظام Minds10 لإنتاج سكريبتات يوتيوب. "
    "مهمتك تفكيك أي مدخل خام (عنوان، فكرة، سؤال، نص) لفهم الموضوع "
    "الظاهري والمشكلة الإنسانية الحقيقية تحته. اكتب بالعربية الفصحى "
    "الواضحة في هذا التحليل الداخلي (مش سكريبت، ده تحليل تقني للفريق)."
)


def understand_input(raw_request: str, audience: str, duration_minutes: int) -> str:
    prompt = f"""
المدخل الخام من المستخدم:
\"\"\"{raw_request}\"\"\"

الجمهور المستهدف: {audience or "غير محدد بدقة، افترض جمهور عام مهتم"}
مدة الفيديو المطلوبة: {duration_minutes} دقيقة

المطلوب تحليل مختصر ومنظم يغطي:
1. الموضوع الظاهري كما صاغه المستخدم.
2. 3-5 احتمالات للمشكلة الإنسانية الحقيقية اللي ممكن تكون تحت الموضوع ده.
3. أي المشكلة من دول الأقرب لصياغة المستخدم وسياقه (اختر واحدة وبرر).
4. هل المدخل يحتاج بحث خارجي لسد فجوة معرفية؟ اذكر الفجوات لو موجودة.
5. هل المدخل يحتوي على مطالب أو قيود صريحة يجب الالتزام بها حرفيًا
   (مثلاً: "من غير تنظير"، "ركز على كذا")؟ اذكرها كما هي.

لا تكتب سكريبت أو هوك أو أي محتوى نهائي هنا — فقط تحليل فهم.
"""
    return gemini_client.generate(prompt, system_instruction=SYSTEM, temperature=0.5)
