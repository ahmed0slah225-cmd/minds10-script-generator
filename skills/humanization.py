"""
skills/humanization.py
========================
المصدر الملهم: harshaneel/humanize (مبادئ عامة، أُعيد بناؤها لتخدم اللهجة
المصرية وسكريبتات يوتيوب طويلة تحديدًا).

الاسم: humanization
الوظيفة: تحسين مسودة مكتوبة بالفعل لتبدو كإنسان بيتكلم فعلاً، وليس نصًا
مولدًا آليًا: تنويع طول الجمل، تقليل الرسمية، إزالة الحشو والتكرار
الآلي، جعل الانتقالات طبيعية.

Input contract:
    - humanize(script_draft: str, context_hint: str = "") -> str
        script_draft: مسودة مكتوبة بالفعل (لا تعمل من الصفر).
        context_hint: أي إرشاد إضافي (مثل بصمة الكاتب الصوتية).

Output contract:
    - نص معاد صياغته إنسانيًا، بنفس المعنى والمعلومات والمصادر تمامًا.

قواعد التشغيل:
    - لا تضيف أي معلومة أو حدث أو تجربة شخصية غير موجودة في المسودة الأصلية.
    - تعمل على مستوى الجملة، الفقرة، الانتقال بين الفقرات، والإيقاع العام.
    - لا تحول النص إلى عامية مبالغ فيها أو غير مفهومة.
    - يجب الحفاظ على المعنى الأصلي والمصادر والحقائق كما هي.

متى تعمل:
    بعد Script Engine (بعد وجود مسودة)، وقبل Final Review/Final Editing.

ما لا يجوز لها فعله:
    - كتابة السكريبت من الصفر.
    - حذف معلومة أو دليل لمجرد أنه "غير سلس".
    - المبالغة في العامية لدرجة تفقد الوضوح.

طريقة الاستدعاء:
    from skills.humanization import HumanizationSkill
    skill = HumanizationSkill()
    ctx.humanized_script = skill.humanize(ctx.script_draft, voice_dna_guidance)
"""

from __future__ import annotations

from llm.gemini_client import generate
from skills.base import BaseSkill

_PERSONA = (
    "أنت 'محرك الإنسنة' (Humanization Engine) لسكريبتات يوتيوب مصرية. "
    "مهمتك إعادة صياغة مسودة مكتوبة بالفعل لتبدو كإنسان مصري بيتكلم فعلاً "
    "أمام كاميرا - وليس نصًا مكتوبًا بشكل مثالي أو رسمي. "
    "نوّع طول الجمل، قلل الحشو والعبارات الجاهزة (مثل 'ومن الجدير بالذكر'، "
    "'في نهاية المطاف')، واجعل الانتقالات بين الأفكار تبدو كلامًا حقيقيًا لا فقرات مترابطة آليًا. "
    "ممنوع منعًا باتًا إضافة أي معلومة أو حدث أو رقم أو مصدر غير موجود في النص الأصلي. "
    "حافظ على كل المعاني والحقائق والمصادر كما هي بالضبط - فقط غيّر الأسلوب."
)


class HumanizationSkill(BaseSkill):
    name = "humanization"
    purpose = "إعادة صياغة مسودة موجودة لتبدو كلامًا إنسانيًا طبيعيًا بدون إضافة أي معلومة جديدة."
    allowed_stages = ("humanization",)
    forbidden = (
        "إضافة معلومات أو تجارب أو أحداث غير موجودة أصلًا",
        "حذف أفكار مهمة",
        "المبالغة في العامية لدرجة فقدان الوضوح",
        "كتابة نص من الصفر",
    )

    def humanize(self, script_draft: str, context_hint: str = "") -> str:
        prompt = f"""
{("إرشاد أسلوبي إضافي:\n" + context_hint) if context_hint else ""}

المسودة الأصلية (أعد صياغتها إنسانيًا فقط، بدون تغيير المعنى أو إضافة معلومات):
{script_draft}

أخرج النص النهائي فقط بدون أي شرح أو تعليق.
"""
        return generate(_PERSONA, prompt, temperature=0.7)
