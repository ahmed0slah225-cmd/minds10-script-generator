# ============================================================
# 5. دالة استدعاء Gemini (تم التصحيح لتناسب المكتبة الجديدة)
# ============================================================

def ask_gemini(client, prompt):
    # تم تغيير طريقة الاستدعاء لتجنب الأخطاء مع مكتبة google-genai
    response = client.models.generate_content(
        model="gemini-2.0-flash", # يمكنك تغييرها إلى gemini-1.5-flash إذا أردت
        contents=prompt
    )
    return response.text


# ============================================================
# 6. حماية حجم السياق
# ============================================================

def trim_text(text, max_chars=18000):
    if not text:
        return ""
    if len(text) <= max_chars:
        return text
    return (
        text[:max_chars]
        + "\n\n"
        "[تم اختصار جزء من السياق للحفاظ على جودة المعالجة.]"
    )


# ============================================================
# 7. بناء Prompt
# ============================================================

def build_prompt(mind, topic, previous_outputs, target_minutes):
    context = ""
    for key, value in previous_outputs.items():
        context += f"\n========================\n{key}\n========================\n{trim_text(value)}\n"

    prompt = f"""
{GLOBAL_RULES}

==================================================
المشروع
==================================================
موضوع الفيديو:
{topic}

مدة الفيديو المستهدفة:
{target_minutes} دقيقة

==================================================
العقل الحالي
==================================================
الاسم: {mind["name"]}
التخصص: {mind["role"]}

==================================================
مهمتك
==================================================
{mind["description"]}

==================================================
مخرجات أعضاء الفريق المرتبطة بمهمتك
==================================================
{context}

==================================================
طريقة التفكير
==================================================
لا تتعامل مع مخرجات العقول السابقة باعتبارها صحيحة تلقائيًا.
إذا كانت قوية: طورها. وإذا كانت ضعيفة: انتقدها وصححها.
قم بدمج أفكارك مع السياق لإنتاج نتيجة أقوى.

==================================================
المخرج المطلوب
==================================================
أعطني مخرجات عملية يستطيع العقل التالي استخدامها مباشرة بدون مقدمات فارغة.
"""
    return prompt


