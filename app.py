# ============================================================
# 5. دالة الاتصال بـ Gemini
# ============================================================

def ask_gemini(client, prompt):

    interaction = client.interactions.create(
        model="gemini-3.6-flash",
        input=prompt
    )

    return interaction.output_text


# ============================================================
# 6. تنظيف النص
# ============================================================

def trim_text(text, max_chars=18000):

    if not text:
        return ""

    if len(text) <= max_chars:
        return text

    return text[:max_chars] + "\n\n[تم اختصار السياق هنا للحفاظ على جودة المعالجة.]"


# ============================================================
# 7. بناء الـPrompt لكل عقل
