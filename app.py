# 3. واجهة المدخلات وتشغيل السلسلة
topic = st.text_area("أدخل موضوع أو فكرة الفيديو الطويل هنا:", height=120, placeholder="مثال: الدليل الشامل لبناء الوعي المالي وإدارة الدخل من الصفر لسن الـ 30")

if st.button("🚀 ابدأ معالجة سكريبت الـ 30 دقيقة", type="primary"):
    if not api_key:
        st.error("يرجى إدخال Gemini API Key في الشريط الجانبي أولاً!")
    elif not topic:
        st.warning("يرجى إدخال فكرة الفيديو!")
    else:
        try:
            client = genai.Client(api_key=api_key)
            current_context = f"الفكرة الأساسية للفيديو الطويل (30 دقيقة):\n{topic}"
            progress_bar = st.progress(0)
            status_text = st.empty()

            st.divider()
            st.subheader("📊 مراحل معالجة العقول للسكريبت الطويل:")

            for i, mind in enumerate(MINDS):
                status_text.text(f"جاري المعالجة بواسطة: {mind['name']}...")
                
                prompt_text = f"""
                أنت تعمل كـ {mind['name']}.
                مهمتك المحددة: {mind['prompt']}

                السياق والمخرجات السابقة حتى الآن:
                ---
                {current_context}
                ---

                تنبيه هام جداً: المطلوب هو إعداد فيديو طويل جداً مدته 30 دقيقة. لا تختصر إطلاقاً وقم بالتوسع في كتابة التفاصيل والشرح والنصوص المباشرة لتغطية المدة المطلوبة.
                """

                interaction = client.interactions.create(
                    model="gemini-3.6-flash",
                    input=prompt_text
                )

                mind_output = interaction.output_text
                current_context += f"\n\n--- [تعديلات {mind['name']}] ---\n{mind_output}"

                with st.expander(f"✅ {mind['name']}", expanded=(i == len(MINDS) - 1)):
                    st.markdown(mind_output)

                progress_bar.progress((i + 1) / len(MINDS))

            status_text.success("🎉 تم الانتهاء من إعداد السكريبت النهائي الشامل (30 دقيقة) بنجاح!")
            
            st.divider()
            st.subheader("📜 السكريبت النهائي الكلي:")
            st.text_area("النتيجة النهائية جاهزة للنسخ:", value=mind_output, height=450)

        except Exception as e:
            st.error(f"حدث خطأ أثناء الاتصال بالـ API: {e}")
