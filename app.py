def trim_text(text, max_chars=12000):
    """
    تقليل حجم مخرجات العقول القديمة قبل تمريرها للعقل التالي.
    نحتفظ بالبداية والنهاية حتى لا يضيع القرار أو الخلاصة.
    """
    if not text:
        return ""

    if len(text) <= max_chars:
        return text

    head_size = int(max_chars * 0.65)
    tail_size = max_chars - head_size

    return (
        text[:head_size]
        + "\n\n"
        + "[... تم اختصار جزء من المخرج للحفاظ على حجم السياق ...]"
        + "\n\n"
        + text[-tail_size:]
    )


def format_context(selected_outputs):
    if not selected_outputs:
        return "لا توجد مخرجات سابقة مرتبطة بهذه المهمة."

    parts = []

    for label, value in selected_outputs.items():
        parts.append(
            f"""
================ {label} ================

{trim_text(value)}

================ نهاية {label} ================
"""
        )

    return "\n".join(parts)


def extract_retry_delay(error_text, default_delay):
    """
    يحاول استخراج مدة الانتظار لو الـ API كتب:
    retry in 40.18s
    """
    match = re.search(
        r"retry(?:\s+in)?\s+([0-9]+(?:\.[0-9]+)?)\s*s",
        error_text,
        flags=re.IGNORECASE,
    )

    if match:
        try:
            return max(1, float(match.group(1)))
        except ValueError:
            pass

    return default_delay


def clean_model_name(name):
    """
    تنظيف اسم الموديل لحذف أي بادئة زائدة
    """
    if not name:
        return ""
    name = name.strip()
    if name.startswith("models/"):
        name = name[len("models/"):]
    return name


def ask_gemini(
    client,
    prompt,
    requested_model,
    fallback_model,
    max_retries=6,
    base_delay=5,
    status_slot=None,
):
    """
    استدعاء Gemini مع:
    - تنظيف اسم الموديل لعدم حدوث خطأ 404.
    - إعادة محاولة عند 429 / 503.
    - احترام مدة Retry لو ظهرت داخل رسالة الخطأ.
    - Fallback لو الموديل غير موجود.
    """

    req_cleaned = clean_model_name(requested_model)
    fall_cleaned = clean_model_name(fallback_model)

    current_model = req_cleaned if req_cleaned else fall_cleaned
    fallback = fall_cleaned if fall_cleaned else current_model

    last_exc = None

    for attempt in range(1, max_retries + 1):

        try:
            response = client.models.generate_content(
                model=current_model,
                contents=prompt,
            )

            text = getattr(response, "text", "") or ""

            if not text.strip():
                raise RuntimeError("تم استلام رد فارغ من الموديل.")

            return text

        except Exception as exc:

            last_exc = exc

            error_text = str(exc)
            error_lower = error_text.lower()

            not_found = (
                "404" in error_text
                or "not_found" in error_lower
                or "not found" in error_lower
                or "no longer available" in error_lower
            )

            overloaded = (
                "429" in error_text
                or "503" in error_text
                or "resource_exhausted" in error_lower
                or "unavailable" in error_lower
                or "overloaded" in error_lower
                or "high demand" in error_lower
                or "quota" in error_lower
            )

            # ------------------------------------------------
            # لو الموديل غير موجود
            # ------------------------------------------------
            if not_found and current_model != fallback:

                if status_slot is not None:
                    status_slot.warning(
                        f"⚠️ الموديل '{current_model}' غير متاح. "
                        f"جاري التجربة بالموديل البديل '{fallback}'."
                    )

                current_model = fallback
                continue

            # ------------------------------------------------
            # لو حصل Rate Limit أو ضغط
            # ------------------------------------------------
            if overloaded and attempt < max_retries:

                exponential_delay = base_delay * (2 ** (attempt - 1))

                retry_delay = extract_retry_delay(
                    error_text,
                    exponential_delay,
                )

                wait_time = max(retry_delay, exponential_delay)

                # سقف حتى لا ينتظر المستخدم وقتًا غير منطقي
                wait_time = min(wait_time, 120)

                if status_slot is not None:
                    status_slot.info(
                        f"⏳ Gemini طلب الانتظار بسبب ضغط أو حد استخدام. "
                        f"المحاولة {attempt}/{max_retries}. "
                        f"الانتظار حوالي {int(wait_time)} ثانية..."
                    )

                time.sleep(wait_time)
                continue

            raise

    raise last_exc


