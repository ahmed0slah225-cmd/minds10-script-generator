def trim_text(text, max_chars=12000):
    if not text or len(text) <= max_chars: return text
    return text[:int(max_chars*0.7)] + "\n\n[... اختصار لضمان المساحة ...]\n\n" + text[-int(max_chars*0.2):]

def format_context(selected_outputs):
    if not selected_outputs: return "لا توجد مخرجات سابقة."
    return "\n".join([f"=== {k} ===\n{trim_text(v)}" for k, v in selected_outputs.items()])

def ask_gemini(client, prompt, model_name, fallback, status_slot):
    for attempt in range(5):
        try:
            resp = client.models.generate_content(model=model_name, contents=prompt)
            return resp.text
        except Exception as e:
            if "429" in str(e) or "503" in str(e):
                status_slot.warning(f"انتظار بسبب الضغط (محاولة {attempt+1})...")
                time.sleep(10 * (attempt + 1))
            else:
                return client.models.generate_content(model=fallback, contents=prompt).text
    return "فشل استخراج النص."

