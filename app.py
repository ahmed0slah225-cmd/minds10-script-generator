# 5. دالة استدعاء Gemini
# ============================================================

def ask_gemini(client, prompt):

    interaction = client.interactions.create(
        model="gemini-3.6-flash",
        input=prompt
    )

    return interaction.output_text


# ============================================================
# 6. تقليل حجم السياق
# ============================================================

def trim_text(text, max_chars=18000):

    if not text:
        return ""

    if len(text) <= max_chars:
        return text

    return (
        text[:max_chars]
        + "\n\n"
        "[تم اختصار جزء من السياق للحفاظ على جودة المعالجة.]"
    )


# ============================================================
# 7. بناء Prompt
# ============================================================

def build_prompt(
    mind,
    topic,
    previous_outputs,
    target_minutes
):

    context = ""

    for key, value in previous_outputs.items():

        context += f"""

==================================================
{key}
==================================================

{trim_text(value)}

"""


    prompt = f"""

{GLOBAL_RULES}


==================================================
موضوع الفيديو
==================================================

{topic}


==================================================
مدة الفيديو
==================================================

{target_minutes} دقيقة


==================================================
العقل الحالي
==================================================

{mind["name"]}


التخصص:

{mind["role"]}


==================================================
مهمتك
==================================================

{mind["description"]}


==================================================
مخرجات العقول السابقة المرتبطة بمهمتك
==================================================

{context}


==================================================
طريقة العمل
==================================================

أنت عضو في فريق.

لا تفترض أن العقول السابقة صحيحة.

افحص عملهم.

إذا وجدت فكرة قوية:
طورها.

إذا وجدت فكرة ضعيفة:
انتقدها.

إذا وجدت تكرارًا:
أزله.

إذا وجدت تناقضًا:
عالجه.

إذا وجدت فرصة أقوى للـRetention:
اقترحها.

لا تكتب كلامًا عامًا.

كل مخرج يجب أن يكون عمليًا وقابلًا للاستخدام من العقل التالي.
"""

    return prompt


