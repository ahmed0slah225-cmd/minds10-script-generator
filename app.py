import os
import streamlit as st
from google import genai
from google.genai import types

st.set_page_config(page_title="Minds — غرفة كتابة السكريبت", page_icon="🧠", layout="wide")

MODELS = {
    "Gemini 3.6 Flash — أساسي": "gemini-3.6-flash",
    "Gemini 3.7 Flash": "gemini-3.7-flash",
}

SYSTEM = r'''
أنت غرفة كتابة سكريبتات يوتيوب احترافية باللغة العربية المصرية الطبيعية.
مهمتك ليست تلخيص المعلومات ولا إعادة صياغة المقالات. مهمتك تحويل أي مدخل إلى مادة فيديو تجعل المشاهد يفهم ويشعر ويريد أن يكمل.

مبادئ الكتابة:
- ابدأ من حياة المشاهد لا من تعريف الموضوع.
- الهوك ليس عنوانًا مقروءًا؛ هو مشكلة أو مفارقة أو سؤال يفتح فجوة فضول حقيقية.
- كل معلومة يجب أن يكون لها وظيفة: تغيير فهم، رفع فضول، بناء حجة، أو دفع القصة.
- استخدم أمثلة مصرية يومية ملموسة، لا أمثلة عامة بلا تفاصيل.
- اكتب كإنسان يتكلم ويفكر: تردد، ملاحظات صغيرة، انتقالات طبيعية، أسئلة داخلية، اعترافات عندما تخدم الفكرة.
- ممنوع النبرة الأكاديمية الباردة، وممنوع الحماس المصطنع، وممنوع الجمل التي تبدو مولدة آليًا.
- لا تضع عناوين من نوع: المقدمة، أولًا، ثانيًا، الخاتمة داخل النص النهائي إلا إذا كانت ضرورية للإخراج.
- لا تكرر الفكرة نفسها بصيغ مختلفة لمجرد زيادة الطول.
- لا تستخدم نصائح عامة محفوظة من نوع "اصحى بدري واشتغل على نفسك" بلا تفسير وسياق.
- لا تخترع دراسات أو أرقامًا أو اقتباسات أو مصادر.
- إذا كان البحث المباشر غير مفعّل، لا تدّع أنك بحثت في الإنترنت.
- إذا كان البحث المباشر مفعّلًا، استخدمه فقط عندما يضيف تحققًا أو مصدرًا أو معلومة حديثة، وليس للحشو.

منهج التفكير الداخلي قبل الكتابة:
1) افهم السؤال الحقيقي خلف الموضوع.
2) حدد ما الذي يهم المشاهد فعلًا ولماذا.
3) استخرج الصراع أو التناقض المركزي.
4) ابنِ مسارًا معرفيًا يتغير فيه فهم المشاهد تدريجيًا.
5) صمم هوكًا قويًا ثم حافظ على الفضول بتحولات حقيقية، لا بتقطيع مصطنع.
6) أدخل الأدلة بعد أن يصبح السؤال مهمًا.
7) اعترض على الفكرة نفسها وابنِ أقوى تفسير ممكن.
8) راجع التكرار واللغة والوضوح والإيقاع قبل إخراج النص.

النتيجة يجب أن تكون سكريبتًا قابلًا للتسجيل، طويلًا بقدر المدة المطلوبة، غنيًا بالمواقف والتفسير والأمثلة، وبصوت مصري طبيعي.
'''


def build_prompt(topic, audience, duration, source_text, web_enabled):
    research_instruction = (
        "البحث المباشر مفعّل: استخدم Google Search عند الحاجة للتحقق من الحقائق، وابنِ الادعاءات المهمة على مصادر موثوقة. "
        "في نهاية السكريبت أضف قسم مصادر مختصر يحتوي على الروابط التي اعتمدت عليها."
        if web_enabled else
        "البحث المباشر غير مفعّل: اعمل فقط على المعرفة المتاحة للنموذج والنصوص التي قدمها المستخدم، ولا تدّع إجراء بحث مباشر."
    )
    return f"""{SYSTEM}\n\nإعداد الحلقة:\n- الموضوع/المدخل: {topic}\n- الجمهور: {audience}\n- المدة المستهدفة: {duration} دقيقة\n- {research_instruction}\n\nمواد المستخدم الإضافية:\n{source_text or 'لا توجد مواد إضافية.'}\n\nنفّذ العمل داخليًا كغرفة كتابة متعددة المراحل: تحليل الموضوع → زاوية المشاهد → الصراع والسؤال → خريطة الأفكار → تصميم الهوك → بناء المواقف والحكايات → الأدلة → المسودة → فحص الاحتفاظ → فحص التكرار → تحرير المصرية الطبيعية → مراجعة المشاهد النهائي.\nلا تعرض سلسلة التفكير الداخلية. اعرض النتيجة النهائية فقط.\n\nأخرج:\n1. عنوانًا مقترحًا قويًا.\n2. سطرًا يوضح الوعد الذي سيحصل عليه المشاهد.\n3. السكريبت كاملًا، جاهزًا للتسجيل.\n4. بعد السكريبت فقط: المصادر المستخدمة إن وُجدت.\n"""

st.title("🧠 Minds — غرفة كتابة السكريبت")
st.caption("ابنِ سكريبتًا من أي فكرة، نص، سؤال أو مادة بحثية — مع تحكم كامل في البحث والموديل.")

with st.sidebar:
    st.header("إعدادات الكتابة")
    model_label = st.selectbox("الموديل", list(MODELS.keys()), index=0)
    model_name = MODELS[model_label]
    web_enabled = st.checkbox("🔎 البحث المباشر من الإنترنت", value=False, help="عند تفعيله يستطيع النموذج استخدام Google Search للتحقق من المعلومات والمصادر.")
    duration = st.slider("مدة الفيديو (دقيقة)", 5, 90, 30)
    audience = st.text_input("الجمهور المستهدف", "شباب وبنات يحبوا الحكي والأمثلة ومش المحاضرات")
    st.divider()
    st.info(f"الموديل الحالي: {model_name}\n\nالبحث: {'مفعّل' if web_enabled else 'متوقف'}")

api_key = st.secrets.get("GEMINI_API_KEY", os.getenv("GEMINI_API_KEY", ""))
if not api_key:
    st.warning("أضف GEMINI_API_KEY في Streamlit Secrets أولًا.")

topic = st.text_area("موضوعك / سؤالك / فكرتك / النص الخام", height=220, placeholder="اكتب أي شيء... حتى لو كان مجرد جملة قصيرة.")
source_text = st.text_area("مواد إضافية اختيارية", height=150, placeholder="اقتباسات، ملاحظات، محتوى كتاب، نتائج بحث سابقة...", key="sources")

if st.button("🚀 اكتب السكريبت", type="primary", use_container_width=True):
    if not api_key:
        st.error("مفتاح Gemini غير موجود. أضفه في Secrets باسم GEMINI_API_KEY.")
    elif not topic.strip():
        st.error("اكتب الموضوع أو الفكرة أولًا.")
    else:
        try:
            client = genai.Client(api_key=api_key)
            config_kwargs = {"system_instruction": SYSTEM, "temperature": 0.85}
            if web_enabled:
                config_kwargs["tools"] = [types.Tool(google_search=types.GoogleSearch())]
            with st.spinner("غرفة الكتابة بتشتغل على الفكرة..."):
                response = client.models.generate_content(
                    model=model_name,
                    contents=build_prompt(topic, audience, duration, source_text, web_enabled),
                    config=types.GenerateContentConfig(**config_kwargs),
                )
            st.success("تم إنشاء السكريبت.")
            st.markdown(response.text)
            st.download_button("⬇️ تحميل السكريبت", response.text, file_name="script.txt", mime="text/plain")
        except Exception as exc:
            st.error(f"حدث خطأ أثناء طلب Gemini: {exc}")
            st.caption("راجع اسم الموديل، مفتاح API، وحصة الـAPI إذا ظهر خطأ من Google.")
