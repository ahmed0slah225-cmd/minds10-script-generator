# 8. بناء Prompt
# ============================================================

def build_prompt(
    mind,
    topic,
    previous_outputs,
    target_minutes
):
    context = ""

    for key, value in previous_outputs.items():
        context += f"""
========================
{key}
========================

{trim_text(value)}

"""

    prompt = f"""
{GLOBAL_RULES}

==================================================
المشروع
==================================================

موضوع الفيديو:
{topic}

مدة الفيديو المستهدفة:
{target_minutes} دقيقة

==================================================
العقل الحالي
==================================================

الاسم:
{mind["name"]}

التخصص:
{mind["role"]}

==================================================
مهمتك
==================================================

{mind["description"]}

==================================================
مخرجات أعضاء الفريق المرتبطة بمهمتك
==================================================

{context if context else "لا توجد مخرجات سابقة. ابدأ من الموضوع نفسه."}

==================================================
طريقة التفكير
==================================================

لا تتعامل مع مخرجات العقول السابقة باعتبارها صحيحة تلقائيًا.

افحصها.

إذا كانت قوية:
طورها.

إذا كانت ضعيفة:
انتقدها.

إذا كانت مكررة:
احذف التكرار.

إذا كانت غير منطقية:
صححها.

إذا كان هناك تعارض:
اختر الحل الأكثر صدقًا وفائدة.

==================================================
ممنوع
==================================================

لا تكتب كلامًا عامًا.

لا تقل:
"يجب أن يكون الفيديو جذابًا."

اشرح كيف يصبح جذابًا.

لا تضف كلمات فقط لزيادة الطول.

لا تكرر نفس الفكرة.

لا تستخدم لغة أكاديمية بلا داعٍ.

==================================================
المخرج المطلوب
==================================================

أعطني مخرجات عملية يستطيع العقل التالي استخدامها مباشرة.
"""

    return prompt

