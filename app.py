def trim_text(text, max_chars=14000):
    if not text:
        return ""
    if len(text) <= max_chars:
        return text
    head = max_chars * 3 // 4
    tail = max_chars - head
    return (
        text[:head]
        + "\n\n[تم اختصار جزء من المخرج للحفاظ على حجم السياق.]\n\n"
        + text[-tail:]
    )


def ask_gemini(client, prompt, model):
    """استدعاء Gemini مع fallback تلقائي لو كان اسم النموذج غير متاح."""
    requested_model = (model or "").strip() or "gemini-3.6-flash"
    fallback_model = "gemini-3.6-flash"

    try:
        response = client.models.generate_content(
            model=requested_model,
            contents=prompt,
        )
    except Exception as exc:
        error_text = str(exc)
        unavailable = (
            "404" in error_text
            or "NOT_FOUND" in error_text
            or "no longer available" in error_text
            or "not found" in error_text.lower()
        )
        if not unavailable or requested_model == fallback_model:
            raise

        response = client.models.generate_content(
            model=fallback_model,
            contents=prompt,
        )

    return getattr(response, "text", "") or ""


def format_context(selected_outputs):
    if not selected_outputs:
        return "لا توجد مخرجات سابقة."

    chunks = []
    for label, value in selected_outputs.items():
        chunks.append(
            f"\n===== {label} =====\n{trim_text(value)}\n===== نهاية {label} =====\n"
        )
    return "\n".join(chunks)


