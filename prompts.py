# -*- coding: utf-8 -*-
"""
كل البرومبتات وتعليمات الأسلوب بتاعة مولّد سكريبتات Minds10 في مكان واحد،
عشان تقدر تعدّل أسلوب الكتابة من غير ما تدخل تلخبط في كود التطبيق نفسه.

الفكرة: بدل ما نوصف الأسلوب بس بالكلام ("اكتب عامي مصري وشيق")، بنديله
كمان مثال قصير مكتوب بالفعل بالأسلوب ده (Few-shot example) - النماذج
اللغوية بتتعلم من مثال ملموس أحسن بكتير من وصف نظري بس.

ملحوظة عن التنويع (Variety):
لو استخدمت نفس الموضوع أو موضوع قريب منه أكتر من مرة، هتلاحظ إن
السكريبتات كانت بتطلع متشابهة جدًا. السبب مش خطأ في الكود، لكنه سلوك
طبيعي للنماذج اللغوية لما بتتحط تحت قواعد صارمة + مثال واحد ثابت، فبتميل
تختار "الاحتمال الأرجح" في كل مرة. عشان نكسر النمط ده، الملف ده فيه:
1. أكتر من مثال أسلوب (STYLE_EXAMPLES) بدل مثال واحد ثابت، بيتم اختيار
   واحد عشوائي منهم في كل توليد.
2. قائمة "زوايا دخول" (HOOK_ANGLES) بيتم اختيار واحدة عشوائية منها
   وحقنها في التعليمات، عشان تجبر الموديل يبدأ بمدخل مختلف كل مرة.
3. رفع الـ temperature/top_p من app.py (راجع generate_script هناك).
"""

import random

# مثال قصير (Hook + مقدمة + جزء واحد) موضوعه مختلف تمامًا عن أي موضوع
# هيتكتب بعدين، غرضه الوحيد إنه يوضح "الشكل والإيقاع" اللي محتاجينه، مش
# إنه يتكرر أو يتقلد حرفيًا.
STYLE_EXAMPLE = """
# الهوك
لو إنت بتفتح تطبيق المذاكرة أو شغلك، وبعد ثانيتين تلاقي نفسك بتتفرج على
فيديوهات مالهاش لازمة، وبعدين تصحى فجأة تلاقي الوقت راح والمهمة لسه زي
ما هي.. إنت مش "كسول" زي ما بتقول لنفسك كل يوم. إنت واقع في فخ نفسي اسمه
"التأجيل"، وأخطر حاجة فيه إنه بيكبر معاك، وكل يوم بتأجل فيه بتخسر ثقتك
في نفسك من غير ما تحس.

# المقدمة
أهلاً بيك في حلقة جديدة من قناة Minds10. النهاردة مش هقولك "بس خد بالك من
وقتك" وخلاص، لأنك سمعت الكلام ده مليون مرة ومحصلش حاجة. هقولك بالظبط عقلك
بيعمل فيك إيه لما بتأجل، وهديك خطوة عملية واحدة تقدر تجربها النهاردة نفسه
وتحس بالفرق. خليك معايا للآخر.

## ليه مخك بيهرب من المهام الصعبة
المفاجأة إن التأجيل مالوش أي علاقة بالكسل أو ضعف الإرادة زي ما إحنا فاكرين.
هو أساسًا وسيلة دفاع عقلية. لما تواجه مهمة حاسس إنها صعبة أو ممكن تفشل
فيها، مخك بيبعت إشارة قلق، والحل الأسهل قدامه إنه "يهرب" منها لحاجة
بسيطة وممتعة زي السوشيال ميديا، عشان يريحك من الإحساس ده فورًا. المشكلة
إن الراحة دي مؤقتة جدًا، وبعدها الإحساس بالذنب بيرجع أقوى.

فكّر معايا كده: هل فعلاً المهمة نفسها هي اللي مرعبة، ولا الصورة اللي
رسمتها في دماغك عنها هي المرعبة؟ في الغالب هتلاقي إن دماغك ضخّم حجم
المهمة لدرجة إنك مبقتش قادر تبدأ فيها أصلاً. وده بالظبط اللي هيصدمك:
أغلب اللي بيأجلوا مش بيأجلوا لأنهم كسالى، بل لأنهم كمالين (Perfectionists)
خايفين يبدأوا حاجة ومطلعش زي ما هما متخيلينها.
""".strip()


# مثال ثاني بأسلوب مختلف شوية (سؤال مباشر بدل موقف يومي) - الهدف إن
# الموديل ميقلدش نفس القالب بالظبط كل مرة. القاعدة نفسها (هوك = مشكلة
# حقيقية مباشرة) لكن الصياغة والمدخل مختلفين.
STYLE_EXAMPLE_B = """
# الهوك
ليه كل مرة تاخد قرار مهم بتلاقي نفسك ندمان بعدها بأسبوع؟ مش لأنك مش
ذكي، ولا لأن حظك وحش. المشكلة إن أنت بتاخد القرار وأنت واقف جوه "الحريق"
- يعني في لحظة ضغط أو خوف أو حماس زايد - وده بالظبط الوقت اللي عقلك
بيكدب عليك فيه أكتر حاجة.

# المقدمة
أهلاً بيك في حلقة جديدة من Minds10. الفيديو ده مش هيقولك "فكر كويس قبل
ما تقرر" لأن الكلام ده مالوش قيمة عملية. هوريك بالظبط عقلك بيعملك إيه
في لحظة اتخاذ القرار، وأديك طريقة واحدة بسيطة تقدر تستخدمها من النهاردة
تقلل بيها القرارات اللي هتندم عليها.

## قاعدة الـ 10-10-10 اللي بتغيّر طريقة تفكيرك في القرارات
في اللحظة اللي بتحس فيها إنك لازم تاخد قرار دلوقتي على طول، جرب تسأل
نفسك 3 أسئلة بس: هل هفتكر القرار ده بعد 10 دقايق؟ هفتكره بعد 10 شهور؟
هفتكره بعد 10 سنين؟ السؤال البسيط ده بيعمل حاجة عبقرية: بيخرجك من
"لحظة الحريق" ويحطك في موقع المراقب اللي بيشوف الصورة الكاملة، مش
بس اللحظة دي.
""".strip()

STYLE_EXAMPLES = [STYLE_EXAMPLE, STYLE_EXAMPLE_B]


# زوايا دخول مختلفة للهوك - بيتم اختيار واحدة عشوائيًا وحقنها في
# التعليمات عشان الموديل يبدأ بمدخل مختلف حتى لو الموضوع اتكرر.
HOOK_ANGLES = [
    "ابدأ الهوك بسؤال مباشر يخلي المشاهد يقول 'ده أنا بالظبط'.",
    "ابدأ الهوك بوصف موقف يومي بسيط ومحدد بيحصل مع المشاهد غالبًا.",
    "ابدأ الهوك باعتراف أو حقيقة صادمة عن الموضوع تخلي المشاهد يوقف يسمع.",
    "ابدأ الهوك بمقارنة قصيرة بين إحساس المشاهد الحالي والإحساس اللي هيوصله لو كمّل الفيديو.",
    "ابدأ الهوك بتصحيح مفهوم شائع غلط عن الموضوع بشكل مباشر ('إنت فاكر إن... بس الحقيقة...').",
    "ابدأ الهوك بجملة قصيرة جدًا وقوية (سطر واحد بس) قبل ما توسّع في المشكلة.",
]


def get_random_style_example() -> str:
    """يختار مثال أسلوب عشوائي من STYLE_EXAMPLES في كل استدعاء."""
    return random.choice(STYLE_EXAMPLES)


def get_random_hook_angle() -> str:
    """يختار زاوية دخول عشوائية للهوك في كل استدعاء."""
    return random.choice(HOOK_ANGLES)


def build_system_instruction(research_mode: str, duration_min: int) -> str:
    """
    research_mode واحدة من التلاتة دول:
      - "none": من غير أي بحث، اعتمادًا على معرفة النموذج بس.
      - "free_search": فيه سياق بحث مجاني (DuckDuckGo) هيتحط في برومبت
        المستخدم، والنموذج المفروض يستخدمه.
      - "paid_grounding": مفعّل أداة Google Search Grounding الرسمية.
    """
    if research_mode == "paid_grounding":
        evidence_rule = (
            "ادعم كل فكرة بدليل أو رقم أو دراسة أو بحث حقيقي لو لقيت مصدر "
            "موثوق بالبحث على الإنترنت."
        )
        source_rule = """
10. لو استخدمت بحث الإنترنت، اذكر مصدر المعلومة بشكل طبيعي جوه الكلام
    (زي "دراسة من جامعة كذا لقت إن..." أو "موقع كذا نشر إحصائية...")
    من غير ما تحط روابط أو أقواس مرجعية جوه النص.
"""
    elif research_mode == "free_search":
        evidence_rule = (
            "ادعم كل فكرة بالمعلومات الموجودة في قسم \"نتائج بحث مبدئي\" "
            "اللي هتلاقيه في طلب المستخدم لو فيه حاجة منها مرتبطة بالفكرة، "
            "واذكر مصدرها بشكل طبيعي من غير أرقام أو أقواس مرجعية."
        )
        source_rule = """
10. لو مفيش في نتائج البحث المبدئي معلومة كافية عن فكرة معينة، متخترعش
    رقم أو دراسة أو مصدر - اتكلم عنها بمنطق عام وأمثلة واقعية بدل كده.
"""
    else:
        evidence_rule = (
            "ادعم كل فكرة بمنطق واضح وأمثلة واقعية من غير ما تدّعي أرقام "
            "أو دراسات محددة."
        )
        source_rule = """
10. معندكش وصول لبحث حي على الإنترنت دلوقتي، فاعتمد على معرفتك العامة
    بس متخترعش أرقام أو أسماء دراسات أو إحصائيات دقيقة وهمية - لو مش
    متأكد من رقم بعينه، اتكلم بشكل عام (زي "دراسات كتير بتقول إن...")
    من غير ما تنسبها لمصدر معين بالاسم.
"""

    min_parts = 3
    max_parts = max(3, min(5, round(duration_min / 8)))

    chosen_example = get_random_style_example()
    chosen_angle = get_random_hook_angle()

    return f"""
انت كاتب سكريبتات يوتيوب محترف ومتخصص في المحتوى العربي، وشغلك إنك تكتب
سكريبتات فيديوهات طويلة (حوالي 30 دقيقة) بالعامية المصرية البسيطة والسهلة،
موجهة لقناة اسمها Minds10.

عشان توضح لك الأسلوب والإيقاع المطلوب بالظبط، ده مثال قصير (مش الموضوع
اللي هتكتب عنه، بس نفس الأسلوب المطلوب منك تتبعه). خد بالك: المثال ده
لتوضيح "الإيقاع" بس - ممنوع تقلد جمله أو أفكاره حرفيًا:

---
{chosen_example}
---

دلوقتي اكتب سكريبت جديد كامل بنفس الإيقاع ده (جمل قصيرة، أسئلة شد
انتباه، ربط الهوك بمشكلة المشاهد)، لكن عن الموضوع اللي هيتقالك في
الطلب، وبصياغة وأمثلة وقصص مختلفة تمامًا عن المثال، مع اتباع القواعد
دي بالحرف:

1. الهوك (Hook): أول 10-15 ثانية لازم تخاطب مشكلة أو ألم حقيقي المشاهد
   عايشه دلوقتي بشكل مباشر وواضح (جملة أو سؤال يلمس تجربته الشخصية فعلاً).
   التزم بالزاوية دي تحديدًا في بداية الهوك: {chosen_angle}
   ابدأ بالمشكلة الحقيقية الأول، وبعد كده لو حابب تستخدم استعارة أو صورة
   أدبية أو قصة قصيرة، استخدمها كطبقة تعميق بعد الجملة الأولى مش كبداية،
   عشان المشاهد يحس فورًا إن الفيديو ده "بيتكلم عنه هو بالذات" قبل أي
   حاجة تانية. ممنوع تبدأ باستعارة مجردة أو مشهد خيالي من غير ما تربطه
   بمشكلة المشاهد في نفس الجملة أو اللي بعدها على طول.
2. المقدمة: قصيرة، تربط الهوك بموضوع الفيديو، وتدي وعد واضح للمشاهد
   بإيه اللي هياخده لو كمّل للآخر.
3. المحتوى الأساسي: قسّم الموضوع لعدد أجزاء رئيسية يتراوح بين {min_parts}
   و{max_parts} بس (مش أكتر)، حتى لو الموضوع فيه زوايا كتير ممكن تتغطى.
   اختار أهم الأفكار وأكتر حاجة هتفيد المشاهد، وادّي كل جزء مساحة ووقت
   كافيين عشان يترسخ صح (شرح + مثال + توضيح لماذا الفكرة دي مهمة)، بدل
   ما تجري على أكبر عدد ممكن من الأفكار بشكل سطحي. كل جزء لازم يكون فيه
   فكرة واحدة رئيسية واضحة، و{evidence_rule}
4. القصص: حط قصة حقيقية (لو لقيتها بالبحث) أو قصة تخيلية واقعية توضح
   الفكرة، بشرط تكون قصيرة ومرتبطة بموضوع الفيديو مباشرة.
5. اللغة: عامية مصرية بسيطة جدًا، زي ما بتتكلم مع صاحبك، من غير فصحى
   تقيلة ومن غير مصطلحات معقدة إلا لو لازم تشرحها بشكل مبسط فورًا.
6. الإيقاع: خلي كل فقرة قصيرة، وكل شوية حط سؤال أو جملة تشد الانتباه
   تاني (زي "بس اللي هيصدمك إن..." أو "وده مش كل حاجة...") عشان محدش
   يمل ويسيب الفيديو من نصه.
7. من غير حشو خالص: كل جملة لازم تضيف معلومة أو مشاعر أو تشويق،
   ممنوع الكلام الفاضي أو التكرار.
8. الخاتمة: لخّص الفكرة الرئيسية في جملتين، واقفل بدعوة واضحة للفعل
   (زي اشتراك أو تعليق) بطريقة طبيعية مش مفتعلة.
9. اكتب السكريبت بعناوين واضحة بصيغة Markdown كالتالي:
   # الهوك
   # المقدمة
   ## [اسم الجزء الأول]
   ## [اسم الجزء الثاني]
   ... (وهكذا لكل الأجزاء، بحد أقصى {max_parts} جزء)
   # الخاتمة
{source_rule}
11. التنويع: تجنب الصياغات الجاهزة والمتكررة (زي "تخيل معايا إنك..."
    كبداية ثابتة، أو نفس ترتيب الأفكار في كل مرة). اختار أمثلة وقصص
    وزاوية سرد أصيلة ومختلفة تناسب الموضوع ده بالذات، حتى لو كتبت قبل
    كده عن موضوع قريب منه.
""".strip()


def build_user_prompt(topic: str, audience: str, tone: str, notes: str,
                       duration_min: int, words_per_minute: int,
                       research_mode: str, research_context: str = "") -> str:
    target_words = int(duration_min * words_per_minute)
    lines = [
        f"اكتب سكريبت فيديو يوتيوب كامل عن الموضوع ده: {topic.strip()}",
        f"مدة الفيديو المستهدفة: {duration_min} دقيقة تقريبًا، يعني السكريبت لازم يكون حوالي "
        f"{target_words} كلمة (زائد أو ناقص 10%)، من غير حشو - لو الموضوع مش هيكفي العدد ده "
        f"بمحتوى حقيقي، وسّع بمناقشة جوانب إضافية للموضوع بدل ما تكرر كلام.",
        f"نبرة الفيديو: {tone}.",
    ]
    if audience.strip():
        lines.append(f"الجمهور المستهدف: {audience.strip()}.")
    if notes.strip():
        lines.append(
            "معلومات أو مصادر إضافية من صاحب القناة، استخدمها في السكريبت في الأماكن المناسبة: "
            f"{notes.strip()}"
        )

    if research_mode == "paid_grounding":
        lines.append(
            "دوّر على الإنترنت على أحدث الأدلة والأرقام والدراسات المتعلقة بالموضوع ده "
            "قبل ما تكتب، واستخدمها في الأجزاء المناسبة بشكل طبيعي."
        )
    elif research_mode == "free_search" and research_context:
        lines.append(
            "نتائج بحث مبدئي من الإنترنت عن الموضوع ده (استخدم اللي مناسب منها بس، "
            "ومتخترعش حاجة زيادة عن اللي فيها):\n" + research_context
        )

    return "\n".join(lines)
